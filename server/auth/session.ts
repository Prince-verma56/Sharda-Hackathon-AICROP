/**
 * Application sessions (created only after a verified OTP).
 *   - token: 32 random bytes (base64url); PostgreSQL stores only its SHA-256
 *   - web: HttpOnly, SameSite=Lax cookie (Secure in production); mobile: `Authorization: Bearer <token>`
 *   - rotation: a new token on every login; the session this browser presented before is revoked
 *   - expiry: 30 days, or 12 hours for accounts with ADMIN / SUPER_ADMIN
 *   - mobile: the Bearer token is a 15-minute ACCESS token; a separate REFRESH token (same row,
 *     only its SHA-256 stored) rotates on every refresh. Presenting an already-rotated refresh token
 *     after a short race window revokes the whole session (token theft / replay).
 *   - Redis caches valid sessions for up to 5 minutes; every revocation deletes the cache entry
 */
import 'server-only';
import { cookies, headers } from 'next/headers';
import type { AppRole } from '@prisma/client';
import { SESSION_COOKIE } from '@/lib/auth/session-cookie';
import { db } from '@/server/db';
import { randomToken, sha256 } from './crypto';

export { SESSION_COOKIE };

const USER_TTL_MS = 30 * 86_400_000;
const STAFF_TTL_MS = 12 * 3_600_000;
const TOUCH_INTERVAL_MS = 5 * 60_000;
const CACHE_TTL_SECONDS = 300;
/** Mobile access tokens are short-lived; the app refreshes them with its refresh token. */
export const MOBILE_ACCESS_TTL_MS = 15 * 60_000;
/** A mobile sign-in never lasts longer than this, however often it is refreshed (staff: 12 h). */
const MOBILE_ABSOLUTE_TTL_MS = 90 * 86_400_000;
/** Two refreshes racing with the same token inside this window are a client race, not theft. */
const REFRESH_RACE_WINDOW_MS = 30_000;

export type SessionClient = 'web' | 'mobile';

export function sessionTtlMs(roles: readonly AppRole[]): number {
  return roles.some((r) => r === 'ADMIN' || r === 'SUPER_ADMIN') ? STAFF_TTL_MS : USER_TTL_MS;
}

function isStaff(roles: readonly AppRole[]) {
  return roles.some((r) => r === 'ADMIN' || r === 'SUPER_ADMIN');
}

function cookieOptions(expires: Date) {
  return {
    httpOnly: true,
    secure: process.env.NODE_ENV === 'production' || (process.env.APP_PUBLIC_URL ?? '').startsWith('https://'),
    sameSite: 'lax' as const,
    path: '/',
    expires,
  };
}

// ---- optional Redis cache --------------------------------------------------------------------

interface CachedSession {
  sessionId: string;
  userId: string;
  expiresAt: string;
}

async function redis() {
  try {
    const { getRedis } = await import('@/server/cache/redis');
    return await getRedis();
  } catch {
    return null;
  }
}

async function cacheGet(tokenHash: string): Promise<CachedSession | null> {
  const client = await redis();
  const raw = client ? await client.get(`session:${tokenHash}`).catch(() => null) : null;
  return raw ? (JSON.parse(raw) as CachedSession) : null;
}

async function cacheSet(tokenHash: string, value: CachedSession, ttlSeconds: number) {
  const client = await redis();
  if (client && ttlSeconds > 0) await client.set(`session:${tokenHash}`, JSON.stringify(value), { EX: ttlSeconds }).catch(() => undefined);
}

async function cacheDel(tokenHashes: string[]) {
  const client = await redis();
  if (client && tokenHashes.length) await client.del(tokenHashes.map((h) => `session:${h}`)).catch(() => undefined);
}

// ---- lifecycle -----------------------------------------------------------------------------

export interface CreatedSession {
  sessionId: string;
  /** web: the cookie value; mobile: the short-lived access token */
  token: string;
  expiresAt: Date;
  /** mobile only */
  refreshToken?: string;
  refreshExpiresAt?: Date;
}

export interface DeviceInfo {
  /** random install id generated by the app (not a hardware identifier) */
  deviceId?: string | null;
  /** e.g. "Android 15 · CropAI 1.0.0" */
  deviceName?: string | null;
}

/** Idle limit for a mobile refresh token (sliding), capped by the absolute sign-in lifetime. */
function refreshExpiry(roles: readonly AppRole[], createdAt: Date, now = Date.now()): Date {
  const absolute = createdAt.getTime() + (isStaff(roles) ? STAFF_TTL_MS : MOBILE_ABSOLUTE_TTL_MS);
  return new Date(Math.min(now + sessionTtlMs(roles), absolute));
}

/** Creates a session after successful OTP verification (rotates any session this client presented). */
export async function createSession(userId: string, roles: readonly AppRole[], client: SessionClient = 'web', device: DeviceInfo = {}): Promise<CreatedSession> {
  const previous = await presentedToken();
  if (previous) await revokeToken(previous.token);

  const userAgent = (await headers()).get('user-agent')?.slice(0, 255) ?? null;
  if (client === 'mobile') return insertMobileSession(userId, roles, { ...device, userAgent });

  const token = randomToken(32);
  const expiresAt = new Date(Date.now() + sessionTtlMs(roles));
  const session = await db.session.create({ data: { tokenHash: sha256(token), userId, client, userAgent, expiresAt } });
  (await cookies()).set(SESSION_COOKIE, token, cookieOptions(expiresAt));
  return { sessionId: session.id, token, expiresAt };
}

/**
 * Stores a new mobile session (access + refresh token hashes). Used by createSession after a
 * verified OTP, and by the development-only test-session script (no request context needed).
 */
export async function insertMobileSession(
  userId: string,
  roles: readonly AppRole[],
  device: DeviceInfo & { userAgent?: string | null } = {},
): Promise<CreatedSession> {
  const now = new Date();
  const token = randomToken(32);
  const refreshToken = randomToken(32);
  const expiresAt = new Date(now.getTime() + MOBILE_ACCESS_TTL_MS);
  const refreshExpiresAt = refreshExpiry(roles, now, now.getTime());
  const session = await db.session.create({
    data: {
      tokenHash: sha256(token),
      userId,
      client: 'mobile',
      userAgent: device.userAgent ?? null,
      expiresAt,
      refreshTokenHash: sha256(refreshToken),
      refreshExpiresAt,
      deviceId: device.deviceId?.slice(0, 64) ?? null,
      deviceName: device.deviceName?.slice(0, 120) ?? null,
      createdAt: now,
    },
  });
  return { sessionId: session.id, token, expiresAt, refreshToken, refreshExpiresAt };
}

export type RefreshResult =
  | { ok: true; sessionId: string; userId: string; accessToken: string; expiresAt: Date; refreshToken: string; refreshExpiresAt: Date }
  | { ok: false; reason: 'INVALID' | 'EXPIRED' | 'REVOKED' | 'REUSED' | 'RACE' | 'ACCOUNT_INACTIVE' };

/**
 * Exchanges a mobile refresh token for a new access + refresh token pair (rotation).
 *   - unknown token                         -> INVALID
 *   - an already-rotated token, within 30 s -> RACE (client should retry with its newest token)
 *   - an already-rotated token, later       -> REUSED, and the whole session is revoked
 *   - revoked / expired session             -> REVOKED / EXPIRED
 *   - account no longer ACTIVE              -> ACCOUNT_INACTIVE (session revoked)
 * Roles are re-read from PostgreSQL so a role removed since sign-in shortens or ends the session.
 */
export async function refreshMobileSession(refreshToken: string, device: DeviceInfo = {}): Promise<RefreshResult> {
  if (typeof refreshToken !== 'string' || refreshToken.length < 32 || refreshToken.length > 128) return { ok: false, reason: 'INVALID' };
  const hash = sha256(refreshToken);
  const now = Date.now();
  const session = await db.session.findUnique({ where: { refreshTokenHash: hash }, include: { user: { select: { status: true, roles: { select: { role: true } } } } } });

  if (!session) {
    const replaced = await db.session.findFirst({ where: { previousRefreshHash: hash, client: 'mobile' }, select: { id: true, rotatedAt: true, revokedAt: true, tokenHash: true } });
    if (!replaced) return { ok: false, reason: 'INVALID' };
    if (replaced.revokedAt) return { ok: false, reason: 'REVOKED' };
    if (replaced.rotatedAt && now - replaced.rotatedAt.getTime() <= REFRESH_RACE_WINDOW_MS) return { ok: false, reason: 'RACE' };
    await db.session.updateMany({ where: { id: replaced.id, revokedAt: null }, data: { revokedAt: new Date() } });
    await cacheDel([replaced.tokenHash]);
    return { ok: false, reason: 'REUSED' };
  }
  if (session.client !== 'mobile') return { ok: false, reason: 'INVALID' };
  if (session.revokedAt) return { ok: false, reason: 'REVOKED' };
  if (!session.refreshExpiresAt || session.refreshExpiresAt.getTime() <= now) return { ok: false, reason: 'EXPIRED' };
  if (session.user.status !== 'ACTIVE') {
    await db.session.updateMany({ where: { id: session.id, revokedAt: null }, data: { revokedAt: new Date() } });
    await cacheDel([session.tokenHash]);
    return { ok: false, reason: 'ACCOUNT_INACTIVE' };
  }

  const roles = session.user.roles.map((r) => r.role);
  const accessToken = randomToken(32);
  const nextRefresh = randomToken(32);
  const expiresAt = new Date(now + MOBILE_ACCESS_TTL_MS);
  const refreshExpiresAt = refreshExpiry(roles, session.createdAt, now);
  if (refreshExpiresAt.getTime() <= now) return { ok: false, reason: 'EXPIRED' };

  // Compare-and-swap on the refresh hash: of two concurrent refreshes only one can win.
  const swapped = await db.session.updateMany({
    where: { id: session.id, refreshTokenHash: hash, revokedAt: null },
    data: {
      tokenHash: sha256(accessToken),
      expiresAt,
      refreshTokenHash: sha256(nextRefresh),
      previousRefreshHash: hash,
      refreshExpiresAt,
      rotatedAt: new Date(now),
      lastSeenAt: new Date(now),
      ...(device.deviceName ? { deviceName: device.deviceName.slice(0, 120) } : {}),
    },
  });
  if (swapped.count !== 1) return { ok: false, reason: 'RACE' };
  await cacheDel([session.tokenHash]); // the previous access token stops working immediately
  return { ok: true, sessionId: session.id, userId: session.userId, accessToken, expiresAt, refreshToken: nextRefresh, refreshExpiresAt };
}

/** Revokes the mobile session that owns this refresh token (logout when the access token is gone). */
export async function revokeByRefreshToken(refreshToken: string): Promise<boolean> {
  if (typeof refreshToken !== 'string' || refreshToken.length < 32 || refreshToken.length > 128) return false;
  const session = await db.session.findUnique({ where: { refreshTokenHash: sha256(refreshToken) }, select: { id: true, tokenHash: true } });
  if (!session) return false;
  await db.session.updateMany({ where: { id: session.id, revokedAt: null }, data: { revokedAt: new Date() } });
  await cacheDel([session.tokenHash]);
  return true;
}

/** The token this request presents: `Authorization: Bearer` (mobile) or the session cookie (web). */
export async function presentedToken(): Promise<{ token: string; via: 'bearer' | 'cookie' } | null> {
  const authorization = (await headers()).get('authorization');
  if (authorization?.toLowerCase().startsWith('bearer ')) {
    const token = authorization.slice(7).trim();
    if (token.length >= 32 && token.length <= 128) return { token, via: 'bearer' };
  }
  const cookie = (await cookies()).get(SESSION_COOKIE)?.value;
  return cookie && cookie.length >= 32 && cookie.length <= 128 ? { token: cookie, via: 'cookie' } : null;
}

export interface ActiveSession {
  sessionId: string;
  userId: string;
  expiresAt: Date;
}

/** Validates a token (secure check: database, with a short Redis cache). */
export async function resolveSession(token: string): Promise<ActiveSession | null> {
  const tokenHash = sha256(token);
  const now = Date.now();
  const cached = await cacheGet(tokenHash);
  if (cached && new Date(cached.expiresAt).getTime() > now) {
    return { sessionId: cached.sessionId, userId: cached.userId, expiresAt: new Date(cached.expiresAt) };
  }
  const session = await db.session.findUnique({ where: { tokenHash } });
  if (!session || session.revokedAt || session.expiresAt.getTime() <= now) return null;
  if (now - session.lastSeenAt.getTime() > TOUCH_INTERVAL_MS) {
    await db.session.update({ where: { id: session.id }, data: { lastSeenAt: new Date() } }).catch(() => undefined);
  }
  const ttl = Math.min(CACHE_TTL_SECONDS, Math.floor((session.expiresAt.getTime() - now) / 1000));
  await cacheSet(tokenHash, { sessionId: session.id, userId: session.userId, expiresAt: session.expiresAt.toISOString() }, ttl);
  return { sessionId: session.id, userId: session.userId, expiresAt: session.expiresAt };
}

async function revokeToken(token: string) {
  const tokenHash = sha256(token);
  await db.session.updateMany({ where: { tokenHash, revokedAt: null }, data: { revokedAt: new Date() } });
  await cacheDel([tokenHash]);
}

/** Logout: revokes the presented session and clears the cookie. */
export async function destroyCurrentSession(): Promise<void> {
  const presented = await presentedToken();
  if (presented) await revokeToken(presented.token);
  (await cookies()).delete(SESSION_COOKIE);
}

/** Revokes every active session of a user (logout everywhere, suspension, role removal). */
export async function revokeAllSessions(userId: string, exceptSessionId?: string): Promise<number> {
  const active = await db.session.findMany({
    where: { userId, revokedAt: null, ...(exceptSessionId ? { id: { not: exceptSessionId } } : {}) },
    select: { id: true, tokenHash: true },
  });
  if (!active.length) return 0;
  await db.session.updateMany({ where: { id: { in: active.map((s) => s.id) } }, data: { revokedAt: new Date() } });
  await cacheDel(active.map((s) => s.tokenHash));
  return active.length;
}

export async function listActiveSessions(userId: string) {
  const now = new Date();
  return db.session.findMany({
    // a mobile session stays active while its refresh token is valid, even between access tokens
    where: { userId, revokedAt: null, OR: [{ expiresAt: { gt: now } }, { refreshExpiresAt: { gt: now } }] },
    select: { id: true, client: true, userAgent: true, deviceName: true, createdAt: true, lastSeenAt: true },
    orderBy: { lastSeenAt: 'desc' },
  });
}
