import 'package:material_ui/material_ui.dart' show GlobalMaterialLocalizations;

import 'generated/app_localizations.dart';

/// Localisation delegates for the app.
///
/// Since Flutter 3.47 the Material and Cupertino widgets live in the `material_ui` /
/// `cupertino_ui` packages, which have their OWN `MaterialLocalizations` /
/// `CupertinoLocalizations` types. The list generated by gen-l10n still registers the framework's
/// delegates, so Hindi screens would have no Material localizations (dialogs, back buttons,
/// date pickers). This list registers the packages' delegates instead.
const List<LocalizationsDelegate<Object?>> appLocalizationsDelegates = [
  AppLocalizations.delegate,
  GlobalMaterialLocalizations.delegate,
  GlobalCupertinoLocalizations.delegate,
  GlobalWidgetsLocalizations.delegate,
];
